  "\\emph{Step 1}: the published test reproduced through the frozen code (unrestricted null); all "
  "fifteen published statistics matched before anything new was computed. "
  f"\\emph{{P1}} (the reading): the published selection set ($2{{,}}566$ genes, "
  f"${tc(S1['n_selected'])}$ usable; background ${tc(S1['n_background'])}$) against a null that permutes "
  f"patients only within the {d['plex_strata']['n_levels']} plexes ({WORD.get(n8, n8)} of $8$ patients, {WORD.get(n9, n9)} of $9$; "
  "none held fixed); its null mean lies "
  f"${'+' if shift >= 0 else '-'}{abs(shift):.3f}$ from step~1's and its s.d.\\ is "
