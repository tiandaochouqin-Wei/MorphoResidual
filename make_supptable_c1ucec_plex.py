"""Build SuppTable_c1ucec_plex.tex from
server_export/results/c1_ucec_plex/ucec_c1/results/posthoc/c1_ucec_plex_reread_result.json
(the single pre-specified run, LSF job 75740140, of
review/POSTHOC_UCEC_C1_PLEX_PRESPEC_2026-10-08.md).

Rounding follows section 4(g) of that file: AUC, null mean, null s.d., margin and p to
3 decimals, z to 2; if rounding would print a value on the other side of a threshold
(0.05 for p, 1.96 for z), decimals are added until it does not.
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
RES = ROOT / "server_export/results/c1_ucec_plex/ucec_c1/results/posthoc"
d = json.loads((RES / "c1_ucec_plex_reread_result.json").read_text(encoding="utf-8"))
assert d["governed_by"] == "review/POSTHOC_UCEC_C1_PLEX_PRESPEC_2026-10-08.md"
assert d["perms"] == 1000 and d["n_cases"] == 138 and d["K"] == 28


def guarded(x, nd, thr):
    """Round x to nd decimals, adding decimals while the rounded value crosses thr."""
    while True:
        s = f"{x:.{nd}f}"
        if (float(s) < thr) == (x < thr) or nd >= 8:
            return s
        nd += 1


def f3(x):
    return f"{x:.3f}"


def fp(p):
    return guarded(p, 3, 0.05)


def fz(z):
    return guarded(z, 2, 1.96)


B = d["perms"]

# Is the usable gene list of P3 identical to step 1's? (saved arrays of the same run)
npz_path = RES / "c1_ucec_plex_reread.npz"
same_genes = None
if npz_path.exists():
    z = np.load(npz_path)
    same_genes = bool(np.array_equal(z["genes"], z["genes_p3"])
                      and np.array_equal(z["sel_mask"], z["sel_mask_p3"]))
else:
    same_genes = all(d["P3"][k] == d["step1"][k] for k in ("n_usable", "n_selected", "n_background"))
assert same_genes, "P3 usable gene list differs from step 1; caption must be changed"


def tc(n):
    """Integer with a LaTeX thousands separator, for use inside math mode."""
    return f"{n:,}".replace(",", "{,}")


WORD = {6: "six", 10: "ten"}


def plex_no(name):
    return name[:2]


sizes = list(d["plex_strata"]["stratum_sizes"].values())
n8, n9 = sizes.count(8), sizes.count(9)
assert len(sizes) == 16 and n8 + n9 == 16 and d["plex_strata"]["n_cases_fixed"] == 0
p3sizes = d["P3"]["strata"]["stratum_sizes"]
p3_changed = {plex_no(k): v for k, v in p3sizes.items() if v != d["plex_strata"]["stratum_sizes"][k]}
assert p3_changed == {"16": 7}, p3_changed
P1, P2, P3, S1 = d["P1"], d["P2"], d["P3"], d["step1"]


def row(name, null, a, n, K):
    return (f"{name} & {null} & {n} & {K} & {f3(a['auc_obs'])} & "
            f"{f3(a['auc_null_mean'])}$\\pm${f3(a['auc_null_sd'])} & {f3(a['margin_auc'])} & "
            f"{fz(a['z_auc'])} & {fp(a['p_auc'])} ({a['exceedances_auc']}) & "
            f"{f3(a['rho_obs'])} & {f3(a['rho_null_mean'])}$\\pm${f3(a['rho_null_sd'])} & "
            f"{fp(a['p_rho'])} \\\\")


shift = P1["null_mean_shift_vs_unrestricted"]
lines = []
