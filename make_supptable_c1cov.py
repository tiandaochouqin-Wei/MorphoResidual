def num(x, d=3):
    return "---" if x in ("", None) else f"{float(x):.{d}f}".replace("-", "$-$")


def fp(p):
    if p in ("", None):
        return "---"
    p = float(p)
    s = f"{p:.3f}"
    if p < 0.05 and s == "0.050":
        s = f"{p:.5f}"
    return s


def n_(x):
    return f"{int(x):,}".replace(",", "{,}")


def sname(s):
    """S_M, T_M|C3, S_M&T_C3, S_M-T_C3 ... as maths."""
    def one(t):
        a, b = t.split("_", 1)
        return f"{a}_{{{BS}mathrm{{{b}}}}}"
    if "&" in s:
        a, b = s.split("&")
        return f"${one(a)}{BS}cap {one(b)}$"
    if "-" in s:
        a, b = s.split("-")
        return f"${one(a)}{BS}setminus {one(b)}$"
    return f"${one(s)}$"


def mname(m):
    if m == "published":
        return "published"
    a, b = m.split("_")
    return f"${a}_{{{BS}mathrm{{{b}}}}}$"


